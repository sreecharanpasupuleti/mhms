    } else {
        $query = $pdo->prepare(
            "SELECT p.patient_id, p.full_name, p.mrn
             FROM patient_assignments a
             JOIN patients p ON a.patient_id = p.patient_id
             WHERE a.doctor_id = ?
             ORDER BY p.full_name, p.patient_id LIMIT 500"
