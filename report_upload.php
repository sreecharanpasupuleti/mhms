<?php
require_once __DIR__ . '/config/db.php';

if (empty($_SESSION['user_id'])) {
    header('Location: login.php');
    exit;
}

$query = $pdo->prepare(
    "SELECT u.role, u.status, d.doctor_id
     FROM users u
     LEFT JOIN doctors d ON u.user_id = d.user_id
     WHERE u.user_id = ?"
);
$query->execute([$_SESSION['user_id']]);
$account = $query->fetch();

if (!$account || $account['status'] !== 'active') {
    $_SESSION = [];
    session_destroy();

    header('Location: login.php');
    exit;
}

if (
    !in_array($account['role'], ['admin', 'doctor'], true)
    || ($account['role'] === 'doctor' && !$account['doctor_id'])
) {
    http_response_code(403);
    exit('An administrator or doctor account is required.');
}

header('Cache-Control: no-store');

$isAdmin = $account['role'] === 'admin';
$doctorId = (int) ($account['doctor_id'] ?? 0);

// Local XAMPP storage only. Configure separately before online deployment.
$storageDirectory = 'C:/xampp/mhms_private_reports';

function reportEscape($value) {
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

function reportPatientAllowed($pdo, $patientId, $isAdmin, $doctorId) {
    if ($isAdmin) {
        $query = $pdo->prepare(
            'SELECT patient_id FROM patients WHERE patient_id = ?'
        );
        $query->execute([$patientId]);
    } else {
        $query = $pdo->prepare(
            'SELECT assignment_id FROM patient_assignments
             WHERE patient_id = ? AND doctor_id = ?'
        );
        $query->execute([$patientId, $doctorId]);
    }

    return (bool) $query->fetchColumn();
}

// Download requests are processed before any HTML is displayed.
if (isset($_GET['download'])) {
    $reportId = filter_input(
        INPUT_GET,
        'download',
        FILTER_VALIDATE_INT,
        ['options' => ['min_range' => 1]]
    );

    if (!$reportId) {
        http_response_code(400);
        exit('Invalid report reference.');
    }

    try {
        $query = $pdo->prepare(
            'SELECT report_id, patient_id, file_path
             FROM lab_reports WHERE report_id = ?'
        );
        $query->execute([$reportId]);
        $report = $query->fetch();

        if (
            !$report
            || !reportPatientAllowed(
                $pdo,
                $report['patient_id'],
                $isAdmin,
                $doctorId
            )
        ) {
            http_response_code(403);
            exit('This report is unavailable to your account.');
        }

        $storedName = $report['file_path'] ?? '';

        // Only accept filenames generated by this module.
        if (!preg_match(
            '/^[a-f0-9]{32}\.(pdf|jpg|png)$/D',
            $storedName
        )) {
            http_response_code(404);
            exit('This report was not stored by the protected upload module.');
        }

        $path = $storageDirectory . '/' . $storedName;

        if (!is_file($path) || !is_readable($path)) {
            http_response_code(404);
            exit('The report file is missing or unreadable.');
        }

        $extension = strtolower(pathinfo($storedName, PATHINFO_EXTENSION));

        logAction(
            $pdo,
            $_SESSION['user_id'],
            $report['patient_id'],
            'DOWNLOAD_REPORT',
            'Report downloaded; report ID ' . $reportId
        );

        header('Content-Type: application/octet-stream');
        header('X-Content-Type-Options: nosniff');
        header(
            'Content-Disposition: attachment; filename="demo-report-'
            . $reportId . '.' . $extension . '"'
        );
        header('Content-Length: ' . filesize($path));

        session_write_close();
        readfile($path);
        exit;

    } catch (PDOException $exception) {
        error_log($exception->getMessage());
        http_response_code(500);
        exit('The report could not be downloaded.');
    }
}

if (empty($_SESSION['report_token'])) {
    $_SESSION['report_token'] = bin2hex(random_bytes(32));
}

$values = [
    'patient_id' => '',
    'test_name' => '',
    'report_date' => date('Y-m-d'),
    'result_summary' => ''
];

$error = '';
$loadError = '';
$patients = [];
$reports = [];

$success = $_SESSION['report_success'] ?? '';
unset($_SESSION['report_success']);

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    foreach ($values as $field => $unused) {
        $input = $_POST[$field] ?? '';
        $values[$field] = is_string($input) ? trim($input) : '';
    }

    $token = $_POST['token'] ?? '';

    $patientId = filter_var(
        $values['patient_id'],
        FILTER_VALIDATE_INT,
        ['options' => ['min_range' => 1]]
    );

    $reportDate = DateTimeImmutable::createFromFormat(
        '!Y-m-d',
        $values['report_date']
    );

    $upload = $_FILES['report_file'] ?? null;

    if (
        !is_string($token)
        || !hash_equals($_SESSION['report_token'], $token)
    ) {
        $error = 'The form expired or the request was too large. '
            . 'Refresh the page and try a small file.';
    } elseif (!$patientId) {
        $error = 'Select a patient.';
    } elseif (
        $values['test_name'] === ''
        || strlen($values['test_name']) > 150
    ) {
        $error = 'Enter a test name of up to 150 characters.';
    } elseif (
        !$reportDate
        || $reportDate->format('Y-m-d') !== $values['report_date']
        || $reportDate > new DateTimeImmutable('today')
    ) {
        $error = 'Enter a valid report date that is not in the future.';
    } elseif (strlen($values['result_summary']) > 5000) {
        $error = 'The summary must not exceed 5,000 characters.';
    } elseif (
        !$upload
        || !isset($upload['error'])
        || !is_int($upload['error'])
        || $upload['error'] !== UPLOAD_ERR_OK
    ) {
        $error = 'The upload did not complete. Select a small file '
            . 'and try again. PHP may have a lower upload-size limit.';
    } elseif (
        !is_string($upload['tmp_name'])
        || !is_uploaded_file($upload['tmp_name'])
    ) {
        $error = 'Invalid uploaded file.';
    } elseif (
        filesize($upload['tmp_name']) === false
        || filesize($upload['tmp_name']) < 1
        || filesize($upload['tmp_name']) > 5 * 1024 * 1024
    ) {
        $error = 'Choose a non-empty file no larger than 5 MB.';
    } elseif (
        !is_dir($storageDirectory)
        || !is_writable($storageDirectory)
    ) {
        $error = 'The private storage folder is missing or not writable. '
            . 'Create C:\\xampp\\mhms_private_reports first.';
    } elseif (!class_exists('finfo')) {
        $error = 'PHP Fileinfo is required to validate uploaded file types.';
    } else {
        $savedPath = null;

        try {
            if (!reportPatientAllowed(
                $pdo,
                $patientId,
                $isAdmin,
                $doctorId
            )) {
                throw new RuntimeException(
                    'This patient is unavailable to your account.'
                );
            }

            $originalName = is_string($upload['name'])
                ? $upload['name']
                : '';

            $extension = strtolower(
                pathinfo($originalName, PATHINFO_EXTENSION)
            );

            $mime = (new finfo(FILEINFO_MIME_TYPE))->file(
                $upload['tmp_name']
            );

            $allowedTypes = [
                'pdf' => 'application/pdf',
                'jpg' => 'image/jpeg',
                'jpeg' => 'image/jpeg',
                'png' => 'image/png'
            ];

            if (
                !isset($allowedTypes[$extension])
                || $allowedTypes[$extension] !== $mime
            ) {
                throw new RuntimeException(
                    'Choose a genuine PDF, JPG, JPEG, or PNG file.'
                );
            }

            $safeExtension = $extension === 'jpeg' ? 'jpg' : $extension;
            $storedName = bin2hex(random_bytes(16))
                . '.' . $safeExtension;

            $savedPath = $storageDirectory . '/' . $storedName;

            if (!move_uploaded_file($upload['tmp_name'], $savedPath)) {
                throw new RuntimeException(
                    'The file could not be stored. Check folder permissions.'
                );
            }

            $pdo->beginTransaction();

            $query = $pdo->prepare(
                'INSERT INTO lab_reports
                 (patient_id, test_name, report_date,
                  result_summary, file_path, uploaded_by)
                 VALUES (?, ?, ?, ?, ?, ?)'
            );

            $query->execute([
                $patientId,
                $values['test_name'],
                $values['report_date'],
                $values['result_summary'] ?: null,
                $storedName,
                $_SESSION['user_id']
            ]);

            $reportId = (int) $pdo->lastInsertId();

            logAction(
                $pdo,
                $_SESSION['user_id'],
                $patientId,
                'UPLOAD_REPORT',
                'Report uploaded; report ID ' . $reportId
            );

            $pdo->commit();
            $savedPath = null;

            $_SESSION['report_success'] =
                'Report uploaded successfully.';

            $_SESSION['report_token'] = bin2hex(random_bytes(32));

            header('Location: report_upload.php');
            exit;

        } catch (PDOException $exception) {
            if ($pdo->inTransaction()) {
                $pdo->rollBack();
            }

            if ($savedPath && is_file($savedPath)) {
                unlink($savedPath);
            }

            error_log($exception->getMessage());
            $error = 'The report record could not be saved. Try again.';

        } catch (RuntimeException $exception) {
            if ($savedPath && is_file($savedPath)) {
                unlink($savedPath);
            }

            $error = $exception->getMessage();
        }
    }
}

try {
    if ($isAdmin) {
        $patients = $pdo->query(
            'SELECT patient_id, full_name, mrn
